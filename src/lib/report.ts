import {
  CATEGORY_META,
  CATEGORY_ORDER,
  STATUS_META,
  formatDuration,
  gradeLabel,
  hostnameOf,
} from "./format";
import type { ApiMeta, CheckItem, CheckStatus, ScanResult } from "./types";

const REPORT_STATUS_ORDER: CheckStatus[] = ["fail", "warn", "pass", "skip", "info"];

function oneLine(value?: string): string {
  return (value ?? "").replace(/\s+/g, " ").trim();
}

function issueLine(check: CheckItem, index: number): string[] {
  const lines = [
    `${index + 1}. **${check.title}** — \`${check.status}\` · ${CATEGORY_META[check.category].label}`,
  ];
  if (check.detail) lines.push(`   - ${oneLine(check.detail)}`);
  if (check.evidence) {
    lines.push("   - Evidence:", "", "     ```", ...check.evidence.split("\n").map((line) => `     ${line}`), "     ```");
  }
  return lines;
}

function checkLine(check: CheckItem): string {
  const detail = check.detail ? ` — ${oneLine(check.detail)}` : "";
  return `- **${check.title}** (\`${check.id}\`)${detail}`;
}

/**
 * Markdown report designed to be pasted straight into an AI coding agent so it
 * can fix the findings. Kept plain and complete: no HTML, no images.
 */
export function buildMarkdownReport(
  result: ScanResult,
  meta?: ApiMeta | null,
): string {
  const finalUrl = result.target.final_url || result.target.url;
  const host = hostnameOf(finalUrl);
  const requestId = meta?.request_id;
  const issues = result.checks.filter(
    (check) => check.status === "fail" || check.status === "warn",
  );

  const lines: string[] = [
    `# Vibe-Check report — ${host}`,
    "",
    `**Grade:** ${result.grade} (${result.score}/100) — ${gradeLabel(result.grade)}`,
    `**Target:** ${result.target.url}`,
  ];

  if (finalUrl !== result.target.url) {
    lines.push(`**Final URL:** ${finalUrl}`);
  }

  lines.push(
    `**Scanned:** ${result.scanned_at}`,
    `**Duration:** ${formatDuration(result.duration_ms)}`,
  );
  if (requestId) lines.push(`**Request ID:** \`${requestId}\``);
  lines.push(
    `**Summary:** ${result.summary.total} checks — ${result.summary.passed} passed, ${result.summary.warnings} warnings, ${result.summary.failed} failed, ${result.summary.skipped} skipped, ${result.summary.info} info`,
    "",
    "## Category breakdown",
    "",
    "| Category | Score | Passed | Warnings | Failed | Skipped |",
    "| --- | ---: | ---: | ---: | ---: | ---: |",
  );

  for (const category of CATEGORY_ORDER) {
    const row = result.categories.find((entry) => entry.category === category);
    if (!row) continue;
    lines.push(
      `| ${CATEGORY_META[category].label} | ${row.score} | ${row.passed} | ${row.warnings} | ${row.failed} | ${row.skipped} |`,
    );
  }

  lines.push("", "## Fix first", "");
  if (issues.length === 0) {
    lines.push("No failed or warning checks. Nice work.");
  } else {
    issues.forEach((check, index) => lines.push(...issueLine(check, index)));
  }

  lines.push("", "## All findings");
  for (const status of REPORT_STATUS_ORDER) {
    const checks = result.checks.filter((check) => check.status === status);
    if (checks.length === 0) continue;
    lines.push("", `### ${STATUS_META[status].plural} (${checks.length})`, "");
    checks.forEach((check) => lines.push(checkLine(check)));
  }

  lines.push(
    "",
    "---",
    "",
    "Generated by Vibe-Check. Findings are passive indicators, not a full penetration test.",
  );

  return `${lines.join("\n")}\n`;
}
